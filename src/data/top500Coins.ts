// Deduplicate strictly by symbol and guarantee 100% unique items with clean 1..N ranks
function createUniqueTopCoins(rawList: Omit<TopCoinInfo, 'rank'>[]): TopCoinInfo[] {
  const seen = new Set<string>();
  const uniqueList: TopCoinInfo[] = [];

  for (const item of rawList) {
    const sym = item.symbol.toUpperCase();
    if (!seen.has(sym)) {
      seen.add(sym);
      uniqueList.push({
        rank: uniqueList.length + 1,
        symbol: sym,
        base: item.base.toUpperCase(),
        quote: 'USDT',
        name: item.name,
        category: item.category,
      });
    }
  }

  return uniqueList;
}

